import { readFileSync } from "node:fs";
import path from "node:path";
import { eq, sql } from "drizzle-orm";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { haversineM } from "@/domain/geo";
import type { Db } from "@/server/db/client";
import { locations, organizations, users, vehicles } from "@/server/db/schema";
import { ctxFromSessionToken, login } from "@/server/auth/session";
import { createImportJob, listImportRows, listTemplates, validateImportJob } from "@/server/import/jobs";
import { buildDemoOrdersXlsx, seedDemo } from "@/server/seed/demo";
import { listCounterparties, listDrivers, truckProfileOf } from "@/server/services/refs";
import { withTestDb } from "../helpers/testDb";

let db: Db;
let close: () => Promise<void>;
let orgId: string;

beforeAll(async () => {
  ({ db, close } = await withTestDb());
  orgId = (await seedDemo(db, { password: "demo-pass-1" })).orgId;
});
afterAll(async () => {
  await close();
});

const ROLES = ["admin", "logist", "warehouse", "finance", "manager"] as const;

describe("seedDemo", () => {
  it("is safe to run twice: one organization and five users", async () => {
    const again = await seedDemo(db, { password: "demo-pass-1" });
    expect(again.orgId).toBe(orgId);
    expect((await db.select().from(organizations)).filter((o) => o.name === "Демо-поставщик")).toHaveLength(1);
    expect(await db.select().from(users).where(eq(users.orgId, orgId))).toHaveLength(5);
    const [{ n }] = await db.select({ n: sql<number>`count(*)::int` }).from(locations).where(eq(locations.orgId, orgId));
    expect(n).toBe(7);
  });

  it("lets each demo user sign in with the given password and their own role", async () => {
    for (const role of ROLES) {
      const session = await login(db, `${role}@demo.local`, "demo-pass-1");
      expect(session, role).not.toBeNull();
      const ctx = await ctxFromSessionToken(db, session!.token);
      expect(ctx?.actor).toMatchObject({ kind: "user", role });
    }
    expect(await login(db, "admin@demo.local", "wrong")).toBeNull();
  });

  it("puts every pair of points closer than 50 km, the limit of a 2GIS demo key", async () => {
    const points = await db.select().from(locations).where(eq(locations.orgId, orgId));
    expect(points.length).toBeGreaterThanOrEqual(7);
    for (const a of points) {
      for (const b of points) {
        expect(haversineM(a, b), `${a.name} — ${b.name}`).toBeLessThan(50_000);
      }
    }
  });

  it("describes a distribution center with a separate gate, rules and a window until 14:00", async () => {
    const [dc] = (await db.select().from(locations).where(eq(locations.orgId, orgId))).filter((l) => l.kind === "dc");
    expect(dc).toMatchObject({ defaultWindowEnd: "14:00", externalKey: "RC-1" });
    expect(dc.entryLat).not.toBeNull();
    expect(dc.entryNotes).toBeTruthy();
    expect(dc.passRules).toBeTruthy();
  });

  it("has three trucks, one of them with an incomplete profile, plus drivers and carriers", async () => {
    const trucks = await db.select().from(vehicles).where(eq(vehicles.orgId, orgId));
    expect(trucks).toHaveLength(3);
    expect(trucks.filter((v) => !truckProfileOf(v).complete)).toHaveLength(1);

    const admin = { db, orgId, actor: { kind: "user" as const, userId: (await db.select().from(users).where(eq(users.email, "admin@demo.local")))[0].id, role: "admin" as const } };
    expect(await listDrivers(admin)).toHaveLength(3);
    expect((await listCounterparties(admin, { kind: "carrier" })).length).toBe(2);
    expect((await listCounterparties(admin, { kind: "customer" })).length).toBeGreaterThanOrEqual(2);
  });

  it("has an import template named Демо", async () => {
    const admin = { db, orgId, actor: { kind: "user" as const, userId: (await db.select().from(users).where(eq(users.email, "admin@demo.local")))[0].id, role: "admin" as const } };
    expect((await listTemplates(admin)).map((t) => t.name)).toEqual(["Демо"]);
  });
});

describe("the demo orders file", () => {
  async function importCheck(bytes: Buffer, filename: string) {
    const admin = { db, orgId, actor: { kind: "user" as const, userId: (await db.select().from(users).where(eq(users.email, "admin@demo.local")))[0].id, role: "admin" as const } };
    const [template] = await listTemplates(admin);
    const { jobId } = await createImportJob(admin, { filename, bytes, templateId: template.id });
    return { admin, jobId, result: await validateImportJob(admin, jobId) };
  }

  it("is generated by code and passes the check with exactly one wrong row", async () => {
    const { admin, jobId, result } = await importCheck(await buildDemoOrdersXlsx(), "orders-demo.xlsx");
    expect(result.errors).toBe(1);
    expect(result.valid).toBeGreaterThanOrEqual(6);
    const [bad] = await listImportRows(admin, jobId, { status: "error" });
    expect(bad.errors[0]).toMatchObject({ field: "locationKey", code: "location_not_found" });
  });

  it("is the same as the file in the repository", async () => {
    const onDisk = readFileSync(path.resolve(__dirname, "../../samples/orders-demo.xlsx"));
    const { result } = await importCheck(onDisk, "orders-demo-disk.xlsx");
    expect(result.errors).toBe(1);
  });
});
